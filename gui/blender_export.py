from __future__ import annotations

import os
from pathlib import Path
import subprocess


def export_prores4444_rgba(fg_video: Path, alpha_video: Path, output_file: Path, ffmpeg_bin: str = "ffmpeg") -> bool:
    # combine despilled foreground and alpha into single prores 4444 container
    cmd = [
        ffmpeg_bin,
        "-y",
        "-i", str(fg_video),
        "-i", str(alpha_video),
        "-filter_complex", "[0:v][1:v]alphamerge[v]",
        "-map", "[v]",
        "-c:v", "prores_ks",
        "-profile:v", "4",
        "-pix_fmt", "yuva444p10le",
        str(output_file),
    ]
    res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return res.returncode == 0


