def export_davinci_pack(fg_video: Path, alpha_video: Path, fill_file: Path, matte_file: Path, ffmpeg_bin: str = "ffmpeg") -> bool:
    # prores 422 hq fill paired with prores 422 alpha matte for davinci resolve external matte node
    cmd_fill = [
        ffmpeg_bin,
        "-y",
        "-i", str(fg_video),
        "-c:v", "prores_ks",
        "-profile:v", "3",
        str(fill_file),
    ]
    cmd_matte = [
        ffmpeg_bin,
        "-y",
        "-i", str(alpha_video),
        "-c:v", "prores_ks",
        "-profile:v", "2",
        str(matte_file),
    ]
    r1 = subprocess.run(cmd_fill, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    r2 = subprocess.run(cmd_matte, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return (r1.returncode == 0) and (r2.returncode == 0)


def generate_blender_import_script(media_path: Path, output_script_path: Path, is_sequence: bool = False) -> None:
    # generates standalone blender python script to auto-wire compositor & 3d cards
    script_content = f'''# auto-generated by corridorkey studio for blender
import bpy
from pathlib import Path

media_file = r"{str(media_path.resolve())}"

# 1. configure compositor
bpy.context.scene.use_nodes = True
tree = bpy.context.scene.node_tree

# clear default composite nodes
for node in list(tree.nodes):
    tree.nodes.remove(node)

# add movie clip or image node
if {is_sequence}:
    node_in = tree.nodes.new(type="CompositorNodeImage")
    node_in.location = (-300, 200)
    # user points to first frame of sequence
else:
    node_in = tree.nodes.new(type="CompositorNodeMovieClip")
    node_in.location = (-300, 200)
    try:
        clip = bpy.data.movieclips.load(media_file)
        node_in.clip = clip
    except Exception as e:
        print("could not auto-load clip:", e)

# add composite output and viewer
node_out = tree.nodes.new(type="CompositorNodeComposite")
node_out.location = (200, 200)

node_view = tree.nodes.new(type="CompositorNodeViewer")
node_view.location = (200, 0)

# link image to composite
if hasattr(node_in, "outputs") and "Image" in node_in.outputs:
    tree.links.new(node_in.outputs["Image"], node_out.inputs["Image"])
    tree.links.new(node_in.outputs["Image"], node_view.inputs["Image"])

print("corridorkey: blender compositor configured successfully.")
'''
    with open(output_script_path, "w", encoding="utf-8") as f:
        f.write(script_content)
